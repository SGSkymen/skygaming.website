function getPlayerPhotoFromBackgrounds(playerElement) {
    let pid = playerElement.id;
    if (pid.startsWith('player')) {
        pid = pid.replace('player', '');
    }
    
    if (window.playerBackgrounds && window.playerBackgrounds[pid]) {
        return window.playerBackgrounds[pid];
    }
    return null;
}

function syncPlayerPhotosOnResize() {
    if (window.innerWidth <= 768) {
        const activePlayer = document.querySelector('.team-player_active');
        if (activePlayer && !activePlayer.querySelector('.team-player__mobile-img')) {
            addMobilePhotoToPlayer(activePlayer);
        }
    } else {
        document.querySelectorAll('.team-player__mobile-img').forEach(photo => photo.remove());
    }
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    
    document.cookie = `locale=${lang}; path=/; max-age=31536000`;
    
    updateTexts(lang);
    updatePlayersContent(lang);
    translatePageContent(lang);
    updateContactsPage(lang);
    updateLanguageButton(lang);
}

function setHTMLWithBreaks(element, text) {
    if (!element || !text) return;
    
    let htmlContent = text.replace(/<br>/g, '<br>');
    
    htmlContent = htmlContent.replace(/<dg>(.*?)<\/dg>/g, '<span class="diagonal-text">$1</span>');
    
    element.innerHTML = htmlContent;

    const diagonalElements = element.querySelectorAll('.diagonal-text');
    diagonalElements.forEach(el => {
        el.style.transform = 'skew(-6deg)';
        el.style.display = 'inline-block';
        el.style.fontStyle = 'italic';
        el.style.willChange = 'transform';
    });
}

function updateTexts(lang) {
    const t = translations[lang];
    
    const navLinks = document.querySelectorAll('.nav__link');
    navLinks.forEach(link => {
        const href = link.getAttribute('href');
        if (href === 'home.html') link.textContent = t.header.home;
        else if (href === 'about.html') link.textContent = t.header.about;
        else if (href === 'team.html') link.textContent = t.header.team;
        else if (href === 'blog.html') link.textContent = t.header.blog;
        else if (href === 'partners.html') link.textContent = t.header.partners;

        if (document.querySelector('.about-page')) {
        const heading = document.querySelector('.about-page .heading');
        if (heading) heading.textContent = t.about.title;
        
        const paragraphs = document.querySelectorAll('.about-page__text p');
        if (paragraphs.length >= 4) {
            setHTMLWithBreaks(paragraphs[0], t.about.text1);
            setHTMLWithBreaks(paragraphs[1], t.about.text2);
            setHTMLWithBreaks(paragraphs[2], t.about.text3);
            setHTMLWithBreaks(paragraphs[3], t.about.text4);
    }};});
  
    const shopLink = document.querySelector('.header__shop-link');
    if (shopLink) shopLink.textContent = t.header.shop;
    
    const heading = document.querySelector('.index-page__heading');
    if (heading) heading.textContent = t.home.title;
    
    const button = document.querySelector('.index-page__btn .btn');
    if (button) button.textContent = t.home.button;
    
    const footerLinks = document.querySelectorAll('.footer__link');
    footerLinks.forEach(link => {
        if (link.getAttribute('href') === 'contacts.html') {
            link.textContent = t.footer.contacts;
        }
    });
    
    const copyright = document.querySelector('.footer__nav-item:last-child');
    if (copyright && !copyright.querySelector('a')) {
        copyright.textContent = t.footer.copyright;
    }

    if (document.querySelector('.blog-page')) {
        const readButtons = document.querySelectorAll('.blog-page-item__btn .btn');
        readButtons.forEach(btn => {
            btn.textContent = t.blog.readMore;
        });
        
        // ✅ ИСПРАВЛЕНО: используем data-article-id
        const items = document.querySelectorAll('.blog-page__item');
        items.forEach((item) => {
            const articleId = parseInt(item.getAttribute('data-article-id'), 10);
            if (articleId) {
                // 🔥 ВАЖНО: Маппинг ID из HTML → ID в translations
                // HTML ID 1 → translations article8
                // HTML ID 2 → translations article7
                // HTML ID 3 → translations article6
                // ...
                // HTML ID 8 → translations article1
                const translationId = 9 - articleId; // 9 - ID = правильный ключ
                const articleKey = `article${translationId}`;
                
                if (t.blog[articleKey]) {
                    const article = item.querySelector('.blog-page-item');
                    if (article) {
                        const title = article.querySelector('.blog-page-item__title');
                        const description = article.querySelector('.blog-page-item__text');
                        
                        if (title) title.textContent = t.blog[articleKey].title;
                        if (description) description.textContent = t.blog[articleKey].description;
                    }
                }
            }
        });
    }
}

function updateContactsPage(lang) {
    const t = translations[lang]?.contacts;
    if (!t) return;
    
    const heading = document.querySelector('.contacts-page__heading .heading');
    if (heading) heading.textContent = t.title;
    
    const description = document.querySelector('.contacts-page__text');
    if (description) description.textContent = t.description;
    
    const mailLabel = document.querySelector('.contacts-page__mail-label');
    if (mailLabel) mailLabel.textContent = t.brandMedia;
    
    const formHeading = document.querySelector('.contacts-page__form-heading .heading');
    if (formHeading) formHeading.textContent = t.formTitle;
    
    const inputs = document.querySelectorAll('.form input, .form textarea');
    inputs.forEach(input => {
        const placeholder = input.getAttribute('placeholder');
        if (placeholder) {
            if (placeholder.includes('Имя') || placeholder.includes('Name')) {
                input.placeholder = t.formName;
            } else if (placeholder.includes('Фамилия') || placeholder.includes('Last Name')) {
                input.placeholder = t.formLastName;
            } else if (placeholder.includes('E-Mail')) {
                input.placeholder = t.formEmail;
            } else if (placeholder.includes('Тема') || placeholder.includes('Subject')) {
                input.placeholder = t.formSubject;
            } else if (placeholder.includes('Сообщение') || placeholder.includes('Message')) {
                input.placeholder = t.formMessage;
            }
        }
    });
    
    const submitBtn = document.querySelector('.form__submit input[type="submit"]');
    if (submitBtn) submitBtn.value = t.formSubmit;
}

function translatePageContent(lang) {
    if (!translations[lang]?.pages) return;
    
    const titleElement = document.querySelector('.article-page__title');
    if (!titleElement) return;
    
    const titleText = titleElement.textContent.toLowerCase();
    const pageMap = {
        'вкусвилл': 'vkusvillPartnership',
        'vkusvill': 'vkusvillPartnership',
        'podkovagold': 'podkovagoldPartnership',
        'cr': 'crPartnership',
        'bscybernews': 'bscPartnership',
        'gpl': 'gplPartnership',
        'ewc': 'ewc2025',
        'ewc': 'ewc2025',

        'эмодзи': 'emojisSkyGaming',
        'emoji': 'emojisSkyGaming',

        'store': 'storeAnnouncement',
        'академи': 'brawlStarsAcademyRoster',
        'academ': 'brawlStarsAcademyRoster',
        'alliance': 'skyGamingAlliance',

    };
    
    let currentPage = null;
    for (const [keyword, page] of Object.entries(pageMap)) {
        if (titleText.includes(keyword)) {
            currentPage = page;
            break;
        }
    }
    
    if (!currentPage) return;
    
    const pageTranslations = translations[lang].pages[currentPage];
    if (!pageTranslations) return;
    
    titleElement.textContent = pageTranslations.title;
    
    const textElements = document.querySelectorAll('.article-page__text p, .article-page__text a');
    let contentIndex = 0;
    
    for (const [key, value] of Object.entries(pageTranslations.content)) {
        if (key.startsWith('p') || key === 'email' || key === 'websiteLink') {
            if (textElements[contentIndex]) {
                textElements[contentIndex].textContent = value;
                contentIndex++;
            }
        }
    }
    
    const backButton = document.querySelector('.back-link');
    if (backButton && pageTranslations.content.backButton) {
        backButton.textContent = pageTranslations.content.backButton;
    }
}

function updatePlayersContent(lang) {
    const roleLabels = document.querySelectorAll('.team-player__info-label');
    roleLabels.forEach(label => {
        if (label.textContent === 'Role' || label.textContent === 'Роль') {
            label.textContent = translations[lang].common.role;
        } else if (label.textContent === 'Bio' || label.textContent === 'Биография') {
            label.textContent = translations[lang].common.bio;
        } else if (label.textContent === 'Socials' || label.textContent === 'Соцсети') {
            label.textContent = translations[lang].common.socials;
        }
    });
    
    const playerElements = document.querySelectorAll('.team-player');
    playerElements.forEach(playerElement => {
        const pid = playerElement.id;
        const player = findPlayerById(pid);
        
        if (player) {
            const nameElement = playerElement.querySelector('.team-player__name');
            if (nameElement && player.name[lang]) {
                nameElement.textContent = player.name[lang];
            }
            
            const roleValue = playerElement.querySelector('.team-player__info-value');
            if (roleValue && player.role[lang]) {
                const roleLabel = roleValue.previousElementSibling;
                if (roleLabel && (roleLabel.textContent === translations[lang].common.role || 
                                 roleLabel.textContent === 'Role' || 
                                 roleLabel.textContent === 'Роль')) {
                    roleValue.textContent = player.role[lang];
                }
            }
            
            const infoItems = playerElement.querySelectorAll('.team-player__info-item');
            if (infoItems.length > 1) {
                const bioValue = infoItems[1].querySelector('.team-player__info-value');
                if (bioValue && player.bio[lang]) {
                    setHTMLWithBreaks(bioValue, player.bio[lang]);
                }
            }
            
            if (infoItems.length > 2) {
                const achievementsValue = infoItems[2].querySelector('.team-player__info-value');
                if (achievementsValue && player.achievements && player.achievements[lang]) {
                    setHTMLWithBreaks(achievementsValue, player.achievements[lang]);
                }
            }
        }
    });
}

document.addEventListener('DOMContentLoaded', function() {
    const currentLang = getCurrentLanguage();
    setLanguage(currentLang);
    
    const langItems = document.querySelectorAll('.lang__item');
    langItems.forEach(item => {
        item.addEventListener('click', function() {
            const lang = this.getAttribute('data-lang');
            setLanguage(lang);
            
            langItems.forEach(i => i.classList.remove('active'));
            this.classList.add('active');
        });
        
        if (item.getAttribute('data-lang') === currentLang) {
            item.classList.add('active');
        }
    });
});

function findPlayerById(elementId) {
    for (const game of Object.values(playersData)) {
        const player = game.find(p => p.pid === elementId);
        if (player) return player;
    }
    return null;
}

function getCurrentLanguage() {
    const cookieValue = document.cookie
        .split('; ')
        .find(row => row.startsWith('locale='))
        ?.split('=')[1];
    
    const browserLang = navigator.language.split('-')[0];
    
    return cookieValue || (translations[browserLang] ? browserLang : 'ru');
}

function updateLanguageButton(lang) {
    const langButton = document.getElementById('langButton');
    if (!langButton) return;
    
    const langItem = langButton.querySelector(`.lang__item[data-lang="${lang}"]`);
    if (langItem) {
        const langItemsContainer = langButton.querySelector('.lang__items');
        const allItems = langButton.querySelectorAll('.lang__item');
        
        if (langItemsContainer) {
            langItemsContainer.prepend(langItem);
        }
    }
}
